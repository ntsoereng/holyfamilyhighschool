const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
let mobileChange;
const mobile = {matches:true,addEventListener(e,fn){mobileChange=fn;}};
const classes = new Set();
const menuEvents = {}, toggleEvents = {}, documentEvents = {};
const toggle = {attributes:{'aria-expanded':'false'},setAttribute(k,v){this.attributes[k]=v;},getAttribute(k){return this.attributes[k];},addEventListener(e,fn){toggleEvents[e]=fn;},contains:x=>x==='toggle',focus(){this.focused=true;}};
let dropdownClosed = false;
const menu = {classList:{toggle(k,v){v?classes.add(k):classes.delete(k);}},addEventListener(e,fn){menuEvents[e]=fn;},contains:x=>x==='menu',querySelectorAll:()=>[{removeAttribute(){dropdownClosed=true;}}]};
const document = {documentElement:{classList:{add(){}}},body:{classList:{contains:()=>false}},querySelector:s=>s==='[data-menu-toggle]'?toggle:menu,querySelectorAll:()=>[],addEventListener(e,fn){documentEvents[e]=fn;}};
vm.runInNewContext(fs.readFileSync('static/js/site.js','utf8'),{document,window:{matchMedia:()=>mobile}});
assert.equal(menu.inert,true);
toggleEvents.click(); assert.equal(menu.inert,false); assert(classes.has('is-open'));
documentEvents.keydown({key:'Escape'}); assert.equal(menu.inert,true); assert(toggle.focused); assert(dropdownClosed);
toggleEvents.click(); documentEvents.click({target:'outside'}); assert.equal(menu.inert,true);
toggleEvents.click(); menuEvents.click({target:{closest:()=>true}}); assert.equal(menu.inert,true);
mobile.matches=false; mobileChange(); assert.equal(menu.inert,false); assert.equal(toggle.attributes['aria-expanded'],'false');
mobile.matches=true; mobileChange(); assert.equal(menu.inert,true);
console.log('Public menu keyboard, outside click, links and breakpoint checks passed.');
